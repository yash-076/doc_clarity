import uuid
from typing import Optional, Literal, List
from pydantic import BaseModel, Field, ConfigDict, field_validator
from app.core.personas import PersonaType


class RAGQuestionRequest(BaseModel):
    """Schema for requesting grounded Q&A on a specific document."""
    question: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="User question about the uploaded document.",
        examples=["What are the exclusions mentioned in this insurance policy?"]
    )
    persona: PersonaType = Field(
        default=PersonaType.CONSUMER,
        description="Explanation persona style (consumer, professional, business)."
    )
    top_k: Optional[int] = Field(
        default=None,
        ge=1,
        le=10,
        description="Optional number of document chunks to retrieve for context (1-10)."
    )

    @field_validator("question")
    @classmethod
    def validate_question_non_empty(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("Question cannot be empty or whitespace only.")
        return stripped


class ReexplainRequest(BaseModel):
    """Schema for re-explaining existing document evidence in a different persona style."""
    question: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="Original question or topic to re-explain."
    )
    persona: PersonaType = Field(
        ...,
        description="Target persona style for explanation (consumer, professional, business)."
    )
    source_chunk_ids: Optional[List[uuid.UUID]] = Field(
        default=None,
        description="Optional list of explicit chunk UUIDs to re-explain without re-running retrieval."
    )


class CitationItem(BaseModel):
    """Schema for source chunk citation."""
    chunk_id: uuid.UUID = Field(..., description="Unique ID of the retrieved document chunk.")
    page_number: Optional[int] = Field(default=None, description="Page number of the chunk if available.")
    section: Optional[str] = Field(default=None, description="Section title or structure header if detected.")
    relevance_score: float = Field(..., description="Cosine similarity relevance score (0.0 to 1.0).")

    model_config = ConfigDict(from_attributes=True)


class RAGAnswerResponse(BaseModel):
    """Structured response for document question answering."""
    document_id: uuid.UUID = Field(..., description="ID of the document queried.")
    question: str = Field(..., description="The user's original question.")
    persona: PersonaType = Field(default=PersonaType.CONSUMER, description="Persona style used for explanation.")
    answer: str = Field(..., description="Grounded answer generated by Gemini LLM or zero-retrieval message.")
    citations: List[CitationItem] = Field(default_factory=list, description="Source citations mapping back to retrieved chunks.")
    confidence: Literal["high", "medium", "low"] = Field(..., description="Confidence heuristic indicator.")
    disclaimer: Optional[str] = Field(
        default="This explanation is based on the uploaded document and is not a substitute for professional legal, insurance, or medical advice.",
        description="Standard domain disclaimer for high-stakes document intelligence."
    )

    model_config = ConfigDict(from_attributes=True)
